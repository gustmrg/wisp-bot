// Turns the user guide in docs/guide into backend/app-guide-content.ts, the
// topics the wisp_help tool serves. The module is committed so every build
// (desktop, server package, Docker) has the guide without copying files; a
// test fails when it is out of date. Run with `npm run guide`.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GUIDE_DIRECTORY = path.join(root, "docs", "guide");
export const GUIDE_MODULE = path.join(root, "backend", "app-guide-content.ts");

const FRONT_MATTER = /^---\n([\s\S]*?)\n---\n+/;

/** Reads one topic: its id is the file name, its title and summary come from the front matter. */
function parseTopic(file, text) {
  const id = path.basename(file, ".md");
  const match = FRONT_MATTER.exec(text.replaceAll("\r\n", "\n"));
  if (!match) throw new Error(`${file} has no front matter.`);
  const fields = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const separator = line.indexOf(":");
      if (separator < 0) throw new Error(`${file}: front matter line without a key: ${line}`);
      return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
    }),
  );
  if (!fields.title || !fields.summary) throw new Error(`${file} needs a title and a summary.`);
  return { id, title: fields.title, summary: fields.summary, body: text.slice(match[0].length).trim() };
}

export async function readGuideTopics(directory = GUIDE_DIRECTORY) {
  const files = (await readdir(directory)).filter((name) => name.endsWith(".md") && name !== "README.md").sort();
  const topics = [];
  for (const file of files) topics.push(parseTopic(file, await readFile(path.join(directory, file), "utf8")));
  // The overview maps every screen, so it is listed first.
  return topics.sort((a, b) => Number(b.id === "overview") - Number(a.id === "overview"));
}

export function renderGuideModule(topics) {
  return [
    "// Generated by scripts/build-app-guide.mjs from docs/guide. Do not edit: change the guide and run `npm run guide`.",
    'import type { AppGuideTopic } from "./app-guide.js";',
    "",
    "export const APP_GUIDE_TOPICS: ReadonlyArray<AppGuideTopic> = [",
    ...topics.map((topic) => `  ${JSON.stringify(topic)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(GUIDE_MODULE, renderGuideModule(await readGuideTopics()));
  console.log(`Wrote ${path.relative(root, GUIDE_MODULE)}.`);
}
